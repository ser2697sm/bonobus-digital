CREATE TABLE bono (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20)  UNIQUE NOT NULL,
    titular VARCHAR(100)    NOT NULL,
    viajes_restantes INTEGER NOT NULL CHECK (viajes_restantes >= 0),
    fecha_creacion  TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE movimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bono_id BIGINT NOT NULL REFERENCES bono(id),
    tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('VIAJE','RECARGA')),
    viajes INTEGER NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_movimiento_bono_fecha ON movimiento (bono_id, fecha);